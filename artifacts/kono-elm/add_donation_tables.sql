  explorer_url_template TEXT DEFAULT 'https://tronscan.org/#/address/{address}',
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT single_row CHECK (id = 1)
);

