-- 2. Create donations table
CREATE TABLE IF NOT EXISTS donations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  transaction_hash TEXT NOT NULL,
  currency TEXT NOT NULL DEFAULT 'USDT',
  network TEXT NOT NULL DEFAULT 'TRON (TRC-20)',
  amount NUMERIC(12, 2) DEFAULT 0,
  donor_name TEXT,
  donor_email TEXT,
  donor_message TEXT,
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'verified', 'rejected')),
  created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- Enable RLS for donations
ALTER TABLE donations ENABLE ROW LEVEL SECURITY;

-- Allow public to insert donation confirmation details
CREATE POLICY "Allow public insert for donations" ON donations FOR INSERT WITH CHECK (true);
-- Only service role (admin) can select or modify donations
CREATE POLICY "Allow service_role full access for donations" ON donations FOR ALL TO service_role USING (true) WITH CHECK (true);

-- Indexes for performance
CREATE INDEX IF NOT EXISTS idx_donations_created_at ON donations(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_donations_status ON donations(status);
CREATE INDEX IF NOT EXISTS idx_donations_tx_hash ON donations(transaction_hash);
